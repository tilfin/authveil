import assert from "node:assert/strict";
import { test } from "node:test";
import { startEchoUpstream, startTestProxy } from "authveil/testkit";
import { buildServer } from "./server.js";

test("accepts the ALB identity generated by AuthVeil", async () => {
  const upstream = await startEchoUpstream();
  const authveil = await startTestProxy({
    upstream: { url: upstream.url },
    identityProxy: {
      type: "alb",
      issuer: "https://authveil.local",
      clientId: "fastify-example",
    },
  });
  const previousJwksUrl = process.env.AUTHVEIL_JWKS_URL;
  process.env.AUTHVEIL_JWKS_URL = `${authveil.address.url}/_authveil/.well-known/jwks.json`;
  const app = buildServer({ logger: false });

  try {
    const login = await fetch(`${authveil.address.url}/_authveil/login?user=admin`, {
      redirect: "manual",
    });
    const cookie = login.headers.get("set-cookie")?.split(";", 1)[0];
    assert.ok(cookie);

    const proxied = await fetch(`${authveil.address.url}/user`, { headers: { cookie } });
    assert.equal(proxied.status, 200);
    const { headers } = await proxied.json();

    const response = await app.inject({ method: "GET", url: "/user", headers });

    assert.equal(response.statusCode, 200);
    assert.deepEqual(response.json(), {
      subject: "local-admin-001",
      email: "admin@example.com",
      name: "Local Admin",
      groups: ["administrators", "developers"],
      claims: {
        groups: ["administrators", "developers"],
        sub: "local-admin-001",
        email: "admin@example.com",
        name: "Local Admin",
      },
    });
  } finally {
    if (previousJwksUrl === undefined) delete process.env.AUTHVEIL_JWKS_URL;
    else process.env.AUTHVEIL_JWKS_URL = previousJwksUrl;
    await app.close();
    await authveil.close();
    await upstream.close();
  }
});
